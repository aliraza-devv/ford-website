// Generates src/config/partBounds.ts from the GT500 glb: the bounding box of
// each assembly actor's parts, in the car's own frame (metres, x lateral with
// +X the driver's side, y up from the tyre contact, z toward the nose,
// centred on the car's footprint). The plant's cranes, carts and spreaders are
// sized from these, so nothing is a guess.
//
//   node scripts/gen-part-bounds.mjs

import fs from "node:fs";
import * as THREE from "three";

const GLB = "public/models/mustang-shelby-gt500.glb";
const OUT = "src/config/partBounds.ts";

// The same regexes the runtime rig uses, against the same normalised names
// (three strips `. [ ] : /` from node names when it loads a glb).
const normalise = (n) => n.replace(/[.[\]:/]/g, "");
const ACTORS = {
  engine: /^GT500(Engine_|Supercharger_|Strutbar_|Transmission_|Radiator_|RadiatorFan_)/,
  tub: /^GT500(Body_|Dash_|Sunvisor_|Seat|Steer_|Gauges_|Screen_|Shifter_|MirrorInt_|Stalk|Pedal|Rollcage_|Fender[LR]_|Windshield|Backlight|SideGlass[LR]_|Wipers)/,
  doorL: /^GT500(DoorL_|DoorGlassL_|MirrorL_|BadgeL_)/,
  doorR: /^GT500(DoorR_|DoorGlassR_|MirrorR_|BadgeR_)/,
  hood: /^GT500Hood_/,
  trunk: /^GT500(Trunk_|Wing_|BadgeRr_)/,
  front: /^GT500(BumperFt_|Headlight[LR]_|HeadlightGlass[LR]_)/,
  rear: /^GT500(BumperRr_|Taillight[LR]_|TaillightGlass[LR]_)/,
};

const buf = fs.readFileSync(GLB);
const len = buf.readUInt32LE(12);
const j = JSON.parse(buf.slice(20, 20 + len).toString());

const parent = new Array(j.nodes.length).fill(-1);
j.nodes.forEach((n, i) => (n.children || []).forEach((c) => (parent[c] = i)));
const world = new Array(j.nodes.length);
function local(n) {
  const m = new THREE.Matrix4();
  if (n.matrix) m.fromArray(n.matrix);
  else {
    m.compose(
      new THREE.Vector3(...(n.translation || [0, 0, 0])),
      new THREE.Quaternion(...(n.rotation || [0, 0, 0, 1])),
      new THREE.Vector3(...(n.scale || [1, 1, 1])),
    );
  }
  return m;
}
function getWorld(i) {
  if (world[i]) return world[i];
  const l = local(j.nodes[i]);
  world[i] = parent[i] < 0 ? l : getWorld(parent[i]).clone().multiply(l);
  return world[i];
}

const boxes = [];
const all = new THREE.Box3();
j.nodes.forEach((n, i) => {
  if (n.mesh === undefined) return;
  const box = new THREE.Box3();
  for (const p of j.meshes[n.mesh].primitives) {
    const a = j.accessors[p.attributes.POSITION];
    for (const x of [a.min[0], a.max[0]])
      for (const y of [a.min[1], a.max[1]])
        for (const z of [a.min[2], a.max[2]]) box.expandByPoint(new THREE.Vector3(x, y, z).applyMatrix4(getWorld(i)));
  }
  all.union(box);
  boxes.push({ name: normalise(n.name), box });
});

// Same centring the runtime applies: x/z on the bounding-box centre, y on its
// floor; then to metres (the car is 4.8 m long).
const size = all.getSize(new THREE.Vector3());
const centre = all.getCenter(new THREE.Vector3());
const k = 4.8 / Math.max(size.x, size.z);
const toCar = (v) => [(v.x - centre.x) * k, (v.y - all.min.y) * k, (v.z - centre.z) * k];

const result = {};
const claimed = new Set();
for (const [id, re] of Object.entries(ACTORS)) {
  const u = new THREE.Box3();
  let count = 0;
  for (const b of boxes) {
    if (!re.test(b.name)) continue;
    u.union(b.box);
    claimed.add(b.name);
    count++;
  }
  const mn = toCar(u.min);
  const mx = toCar(u.max);
  result[id] = { min: mn.map((v) => +v.toFixed(3)), max: mx.map((v) => +v.toFixed(3)), meshes: count };
}

// Everything no actor claims is the rolling chassis.
const chassis = new THREE.Box3();
let cn = 0;
for (const b of boxes) {
  if (claimed.has(b.name)) continue;
  chassis.union(b.box);
  cn++;
}
result.chassis = {
  min: toCar(chassis.min).map((v) => +v.toFixed(3)),
  max: toCar(chassis.max).map((v) => +v.toFixed(3)),
  meshes: cn,
};

const ts = `// GENERATED by scripts/gen-part-bounds.mjs from the GT500 glb. Do not edit.
//
// Bounding box of each assembly actor's parts in the car's own frame, in
// metres: x lateral (+X is the driver's side), y up from the tyre contact, z
// toward the nose, centred on the footprint.

export type PartBox = { min: [number, number, number]; max: [number, number, number]; meshes: number };

export const PART_BOUNDS = ${JSON.stringify(result, null, 2)} as const satisfies Record<string, PartBox>;
`;
fs.writeFileSync(OUT, ts);
console.log(ts);
