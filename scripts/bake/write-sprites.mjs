// Writes src/config/carSprites.ts from the sprites' measurements (scripts/bake/meta.json), which
// both scripts/bake-cars.mjs (a 3D render) and scripts/cut-cars.mjs (a photograph) fill in.

import fs from "node:fs";
import path from "node:path";

export function writeSprites(root, meta) {
  const entries = Object.entries(meta)
    .map(([id, m]) => `  ${JSON.stringify(id)}: { src: ${JSON.stringify(m.src)}, width: ${m.width}, height: ${m.height}, span: ${m.span}, density: ${m.density}, horizon: ${m.horizon}, contact: ${m.contact}, centre: ${m.centre} },`)
    .join("\n");
  fs.writeFileSync(
    path.join(root, "src", "config", "carSprites.ts"),
    `// GENERATED by scripts/bake-cars.mjs and scripts/cut-cars.mjs. Do not edit by hand.
//
// The cars the road finder stands in its road: each a picture of its model, with its size and
// where its horizon and its middle fall.

export const CAR_SPRITES = {
${entries}
} as const;
`,
  );
}
