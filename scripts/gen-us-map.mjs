// Builds src/config/usMap.ts: the contiguous United States as projected path data, plus
// the Ford plants' positions in the same projection.
//
//   npm i --no-save us-atlas@3 topojson-client@3 d3-geo@3
//   node scripts/gen-us-map.mjs
//
// Source: the US Census Bureau cartographic boundary files, redistributed by the
// us-atlas package (public domain; ISC for the package). The projection is d3's
// Albers (conic equal-area, the usual one for a map of the lower 48), fitted to a
// 1600 x 1000 box. Everything is baked here so the page ships plain path strings and
// needs no map library at runtime.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { geoAlbers, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("us-atlas/states-10m.json");

const OUT = process.argv[2] ?? path.resolve("src/config/usMap.ts");
const W = 1600;
const H = 1000;

// The lower 48 and DC. (FIPS codes of the states we leave out: Alaska 02, Hawaii 15,
// and the territories 60+.)
const SKIP = new Set(["02", "15", "60", "66", "69", "72", "78"]);
const states = feature(topo, topo.objects.states).features.filter((f) => !SKIP.has(f.id));

const projection = geoAlbers().fitExtent(
  [
    [0, 0],
    [W, H],
  ],
  { type: "FeatureCollection", features: states },
);
const pathGen = geoPath(projection).digits(1);

const POSTAL = {
  "01": "AL", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC", "12": "FL",
  "13": "GA", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY", "22": "LA", "23": "ME",
  "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT", "31": "NE", "32": "NV",
  "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH", "40": "OK", "41": "OR",
  "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT", "50": "VT", "51": "VA",
  "53": "WA", "54": "WV", "55": "WI", "56": "WY",
};

// Ford's U.S. assembly plants (corporate.ford.com, Worldwide Locations, June 2026) at the
// coordinates Wikipedia gives for each site.
const PLANTS = [
  { id: "flat-rock", lat: 42.10694, lon: -83.24778 },
  { id: "michigan-assembly", lat: 42.27667, lon: -83.40889 },
  { id: "dearborn-truck", lat: 42.305, lon: -83.165 },
  { id: "ohio-assembly", lat: 41.4908639, lon: -82.0652722 },
  { id: "chicago-assembly", lat: 41.66194, lon: -87.56083 },
  { id: "kansas-city", lat: 39.202329, lon: -94.480534 },
  { id: "kentucky-truck", lat: 38.2939444, lon: -85.5317611 },
  { id: "louisville-assembly", lat: 38.158587, lon: -85.718937 },
];

const round1 = (n) => Math.round(n * 10) / 10;

const out = [];
for (const f of states) {
  const d = pathGen(f);
  if (!d) continue;
  const [[x0, y0], [x1, y1]] = pathGen.bounds(f);
  out.push({ id: POSTAL[f.id], name: f.properties.name, d, bbox: [x0, y0, x1, y1].map(round1) });
}
out.sort((a, b) => a.id.localeCompare(b.id));

const plantXY = {};
for (const p of PLANTS) {
  const [x, y] = projection([p.lon, p.lat]);
  plantXY[p.id] = [round1(x), round1(y)];
}

const states_ts = out
  .map((s) => `  { id: ${JSON.stringify(s.id)}, name: ${JSON.stringify(s.name)}, bbox: ${JSON.stringify(s.bbox)}, d: ${JSON.stringify(s.d)} },`)
  .join("\n");

const file = `// GENERATED by scripts/gen-us-map.mjs. Do not edit by hand.
//
// The lower 48 states as Albers-projected SVG path data in a ${W} x ${H} box, from the US
// Census Bureau cartographic boundaries (public domain, via the us-atlas package), and the
// Ford assembly plants' positions in the same projection.

export const MAP_SIZE = { width: ${W}, height: ${H} } as const;

export type MapState = {
  /** USPS code. */
  id: string;
  name: string;
  /** Bounding box in map units: [minX, minY, maxX, maxY]. */
  bbox: [number, number, number, number];
  /** SVG path data, in map units. */
  d: string;
};

export const MAP_STATES: MapState[] = [
${states_ts}
];

/** Plant positions in map units, by plant id (see config/fordPlants.ts). */
export const PLANT_XY: Record<string, [number, number]> = ${JSON.stringify(plantXY, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file);
if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify({ size: { width: W, height: H }, states: out, plants: plantXY }));
const bytes = Buffer.byteLength(file);
console.log(`wrote ${OUT}: ${out.length} states, ${(bytes / 1024).toFixed(1)} KB`);
console.log("plants:", JSON.stringify(plantXY));
