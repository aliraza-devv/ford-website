// Bakes the loader's car: the GT500 in profile, from the model in public/models, as
//
//   public/loader/gt500.webp         the car without its wheels, and its reflection on the road
//   public/loader/gt500-wheel.webp   one wheel, which the loader spins
//   src/config/loaderCar.ts          where the wheels, the lamps and the tyres' line fall in it
//
//   node scripts/bake-loader-car.mjs [--shot]
//
// --shot writes reference/compare/loader-car.png (the pieces put together on a dark road).

import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { chromium } from "playwright-core";
import { addReflection } from "./bake/reflect.mjs";

const sharp = createRequire(import.meta.url)("sharp");
const ROOT = path.resolve(".");
const SHOT = process.argv.includes("--shot");

const MIME = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".json": "application/json", ".glb": "model/gltf-binary", ".webp": "image/webp", ".png": "image/png" };
const server = http.createServer((req, res) => {
  const url = decodeURIComponent((req.url ?? "/").split("?")[0]);
  const file = path.join(ROOT, url);
  if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
    res.writeHead(404);
    res.end("not found");
    return;
  }
  res.writeHead(200, { "Content-Type": MIME[path.extname(file)] ?? "application/octet-stream", "Cache-Control": "no-store" });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(5180, "127.0.0.1", r));

const { PROFILE } = await import("./bake/specs.mjs");
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--ignore-gpu-blocklist", "--enable-gpu-rasterization", "--use-angle=d3d11"] });
const page = await browser.newPage({ viewport: { width: 1200, height: 700 } });
page.on("pageerror", (e) => console.log("PAGE ERROR", String(e)));
await page.goto("http://127.0.0.1:5180/scripts/bake/bake.html");
await page.waitForFunction(() => window.bakeReady === true, null, { timeout: 60000 });
console.log("baking the loader's car...");
const r = await page.evaluate((spec) => window.bakeProfile(spec), PROFILE);
await browser.close();
server.close();

const decode = async (url) => {
  const { data, info } = await sharp(Buffer.from(url.split(",")[1], "base64")).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data, w: info.width, h: info.height };
};
const body = await decode(r.body);
const full = await decode(r.full);
const m = r.meta;

// the reflection comes from the whole car, the car itself from the picture without wheels
const reflected = addReflection(full.data, full.w, full.h, m.ground, m.span);
const out = Buffer.from(reflected.rgba);
body.data.copy(out, 0, 0, (m.ground + 1) * body.w * 4); // rows 0..ground from the body
const outDir = path.join(ROOT, "public", "loader");
fs.mkdirSync(outDir, { recursive: true });
await sharp(out, { raw: { width: reflected.width, height: reflected.height, channels: 4 } })
  .webp({ quality: 90, alphaQuality: 100, effort: 6 })
  .toFile(path.join(outDir, "gt500.webp"));
await sharp(Buffer.from(r.wheel.split(",")[1], "base64")).webp({ quality: 92, alphaQuality: 100, effort: 6 }).toFile(path.join(outDir, "gt500-wheel.webp"));

const W = reflected.width;
const H = reflected.height;
const f = (v, of) => +(v / of).toFixed(5);
const lines = `// GENERATED by scripts/bake-loader-car.mjs. Do not edit by hand.
//
// The loader's car (public/loader): where its parts fall in the picture, as fractions of its
// width (x) and of its height (y), so the page can place them at any size.

export const LOADER_CAR = {
  src: "/loader/gt500.webp",
  wheelSrc: "/loader/gt500-wheel.webp",
  width: ${W},
  height: ${H},
  /** The picture's height over its width. */
  aspect: ${f(H, W)},
  /** The row the tyres touch, over the picture's height. */
  ground: ${f(m.ground, H)},
  /** The car's own length in the picture, over its width, and where it starts. */
  span: ${f(m.span, W)},
  /** A wheel's picture is this wide, over the car picture's width; a tyre is this wide. */
  wheel: ${f(m.wheelSide, W)},
  tyre: ${f(m.wheelDiameter, W)},
  front: { x: ${f(m.front[0], W)}, y: ${f(m.front[1], H)} },
  rear: { x: ${f(m.rear[0], W)}, y: ${f(m.rear[1], H)} },
  headlamp: { x: ${f(m.headlamp[0], W)}, y: ${f(m.headlamp[1], H)} },
  taillamp: { x: ${f(m.taillamp[0], W)}, y: ${f(m.taillamp[1], H)} },
  nose: ${f(m.nose, W)},
  tail: ${f(m.tail, W)},
} as const;
`;
fs.writeFileSync(path.join(ROOT, "src", "config", "loaderCar.ts"), lines);
console.log(`  ${W}x${H}, ground ${m.ground}, wheel ${m.wheelDiameter}px (sprite ${m.wheelSide}), front ${m.front}, rear ${m.rear}`);

if (SHOT) {
  const wheel = await sharp(Buffer.from(r.wheel.split(",")[1], "base64")).png().toBuffer();
  const base = await sharp(out, { raw: { width: W, height: H, channels: 4 } }).png().toBuffer();
  const place = (c) => ({ input: wheel, left: Math.round(c[0] - m.wheelSide / 2), top: Math.round(c[1] - m.wheelSide / 2) });
  fs.mkdirSync(path.join(ROOT, "reference", "compare"), { recursive: true });
  await sharp({ create: { width: W, height: H, channels: 4, background: { r: 8, g: 14, b: 32, alpha: 1 } } })
    .composite([{ input: base }, place(m.front), place(m.rear)])
    .png()
    .toFile(path.join(ROOT, "reference", "compare", "loader-car.png"));
}
console.log("done");
